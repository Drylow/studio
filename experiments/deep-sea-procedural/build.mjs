import { build } from 'esbuild';
import { mkdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const here = path.dirname(fileURLToPath(import.meta.url));
const sleep = process.argv.includes('--sleep');
const forward = process.argv.includes('--forward');
const destination = path.join(here, forward ? 'dist-forward' : sleep ? 'dist-sleep' : 'dist');
await mkdir(destination, { recursive: true });
await build({ entryPoints: [path.join(here, forward ? 'sleep-forward-scene.mjs' : sleep ? 'sleep-illustrated-scene.mjs' : 'scene.mjs')], outfile: path.join(destination, 'scene.js'), bundle: true, format: 'iife', platform: 'browser', target: 'es2022', minify: true, loader:{'.png':'dataurl'} });
await copyFile(path.join(here, forward ? 'forward-index.html' : sleep ? 'sleep-index.html' : 'index.html'), path.join(destination, 'index.html'));
await copyFile(path.join(here,'node_modules/three/LICENSE'),path.join(destination,'THREE-LICENSE.txt'));
console.log(`Offline ${forward ? 'forward-camera marine preview' : sleep ? 'illustrated five-minute sleep loop' : '24-second study'} built. No runtime API calls.`);
