import { build } from 'esbuild';
import { mkdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const here = path.dirname(fileURLToPath(import.meta.url));
const sleep = process.argv.includes('--sleep');
const destination = path.join(here, sleep ? 'dist-sleep' : 'dist');
await mkdir(destination, { recursive: true });
await build({ entryPoints: [path.join(here, sleep ? 'sleep-scene.mjs' : 'scene.mjs')], outfile: path.join(destination, 'scene.js'), bundle: true, format: 'iife', platform: 'browser', target: 'es2022', minify: true });
await copyFile(path.join(here, sleep ? 'sleep-index.html' : 'index.html'), path.join(destination, 'index.html'));
await copyFile(path.join(here,'node_modules/three/LICENSE'),path.join(destination,'THREE-LICENSE.txt'));
console.log(`Offline ${sleep ? 'five-minute sleep loop' : '24-second study'} built. No image or generation API is used.`);
